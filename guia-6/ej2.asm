NODO_SIZE EQU 8
VAL EQU 0
SIG EQU 4

; CREAR_NODO:
; PUSH << VALOR >>
; CALL CREAR_NODO
; ADD SP, 8
; DEVUELVE EN EAX LA DIR DE UN NODO CON EL VALOR PASADO COMO PARAMETRO Y SIG = NULL

CREAR_NODO: PUSH BP
    MOV BP, SP

    PUSH NODO_SIZE
    CALL ALLOC
    ADD SP, 4

    CMP EAX, NULL
    JZ NODO_FIN

    MOV [EAX + VAL], [BP + 8]
    MOV [EAX + SIG], NULL

NODO_FIN: POP BP
    RET

; INSERTAR_ORDENADO:
; PUSH << -> NODO NUEVO >>
; PUSH << -> -> HEAD >>
; CALL INSERTAR_ORDENADO
; ADD SP, 8

INSERTAR_ORDENADO: PUSH BP
    MOV BP, SP
    PUSH EAX
    PUSH EBX
    PUSH EDX
    
    MOV EDX, [BP + 8]
    MOV EAX, [BP + 12]

    CMP EAX, NULL
    JZ INS_FIN

INS_OTRO: MOV EBX, [EDX]
    CMP EBX, NULL
    JZ INS_ACTUAL
    CMP [EBX + VAL], [EAX + VAL]
    JNN INS_ACTUAL
    MOV EDX, EBX
    ADD EDX, SIG
    JMP INS_OTRO

INS_ACTUAL: MOV [EAX + SIG], EBX
    MOV [EDX], EAX

INS_FIN: POP EDX
    POP EBX
    POP EAX
    MOV SP, BP
    POP BP
    RET

; ELIMINAR:
; PUSH << VALOR >>
; PUSH << -> HEAD >>
; CALL ELIMINAR
; ADD SP, 4

ELIMINAR: PUSH BP
    MOV BP, SP
    PUSH EAX
    PUSH EBX
    PUSH ECX

    MOV EAX, [BP + 12]; VALOR
    MOV ECX, [BP + 8]; -> HEAD

ELIMINAR_OTRO: MOV EBX, [ECX]; ACT
    CMP EBX, NULL
    JZ ELIMINAR_FIN

    CMP [EBX + VAL], EAX
    JZ ELIMINAR_ACTUAL

    MOV ECX, EBX
    ADD ECX, SIG
    JMP ELIMINAR_OTRO

ELIMINAR_ACTUAL: MOV EBX, [EBX + SIG]
    MOV [ECX], EBX

ELIMINAR_FIN: POP ECX
    POP EBX
    POP EAX
    MOV SP, BP
    POP BP
    RET

; BUSCAR:
; PUSH << VALOR >>
; PUSH << -> HEAD >>
; CALL BUSCAR
; ADD SP, 4
; DEVUELVE EN EAX LA DIR O NULL SI NO SE ENCONTRO

BUSCAR: PUSH BP
    MOV BP, SP
    PUSH EBX

    MOV EBX, [BP + 12]; VALOR
    MOV EAX, [BP + 8]; -> HEAD
    MOV EAX, [EAX]; ACT

BUSCAR_OTRO: CMP EAX, NULL
    JZ BUSCAR_FIN

    CMP [EAX + VAL], EBX
    JZ BUSCAR_FIN

    MOV EAX, [EAX + SIG]
    JMP BUSCAR_OTRO

BUSCAR_FIN: POP EBX
    MOV SP, BP
    POP BP
    RET

; IMPRIMIR:
; PUSH << -> HEAD >>
; CALL IMPRIMIR
; ADD SP, 4

IMPRIMIR: PUSH BP
    MOV BP, SP
    PUSH EAX
    PUSH EBX
    PUSH ECX
    PUSH EDX


    MOV EBX, [BP + 8]
    MOV EBX, [EBX]

IMPRIMIR_OTRO: CMP EBX, NULL
    JZ IMPRIMIR_FIN

    MOV EDX, EBX
    ADD EDX, VAL
    LDL ECX, 1
    LDH ECX, 4
    MOV EAX, 0x01
    SYS 2

    MOV EBX, [EBX + SIG]
    JMP IMPRIMIR_OTRO

IMPRIMIR_FIN: POP EDX
    POP ECX
    POP EBX
    POP EAX
    MOV SP, BP
    POP BP
    RET