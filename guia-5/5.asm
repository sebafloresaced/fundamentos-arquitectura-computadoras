; PUSH <<PUNTERO EXPRESION>>
; CALL RPN
; ADD SP, 4
; DEVUELVE EL RESULTADO EN EAX

RPN: PUSH BP
MOV BP, SP
PUSH EBX
PUSH ECX
PUSH EDX

MOV EDX, [BP + 8]; EDX = puntero a la expresion

ITERAR: CMP b[EDX], 0
JZ FIN_RPN
CMP b[EDX], ' '
JZ ESPACIO

CMP b[EDX], '+'
JZ SUMAR
CMP b[EDX], '-'
JZ RESTAR
CMP b[EDX], '*'
JZ MULTIPLICAR
CMP b[EDX], '/'
JZ DIVIDIR

; si no es espacio ni operador, asumimos que comienza un numero
MOV EBX, 0

LEER_NUMERO:
CMP b[EDX], ' '
JZ FIN_NUMERO
CMP b[EDX], 0
JZ FIN_NUMERO

MUL EBX, 10
ADD EBX, b[EDX]
SUB EBX, '0'
ADD EDX, 1
JMP LEER_NUMERO

FIN_NUMERO:
PUSH EBX
JMP ITERAR

ESPACIO:
ADD EDX, 1
JMP ITERAR

SUMAR: POP ECX; ECX = operando 2
POP EAX; EAX = operando 1
ADD EAX, ECX
PUSH EAX
ADD EDX, 1
JMP ITERAR

RESTAR: POP ECX; operando 2
POP EAX; operando 1
SUB EAX, ECX
PUSH EAX
ADD EDX, 1
JMP ITERAR

MULTIPLICAR: POP ECX
POP EAX
MUL EAX, ECX
PUSH EAX
ADD EDX, 1
JMP ITERAR

DIVIDIR: POP ECX
POP EAX
DIV EAX, ECX
PUSH EAX
ADD EDX, 1
JMP ITERAR

FIN_RPN: POP EAX; resultado final
POP EDX
POP ECX
POP EBX
POP BP
RET